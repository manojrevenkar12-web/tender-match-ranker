"""reports/results.json and docs/REPORT.md, generated from runs/. Never edited by hand."""

from __future__ import annotations

import datetime as dt
import json
from typing import Any

from .. import config

LABELS = {
    "rules": "Current rules (buyer's trade label, experience, distance)",
    "lambdamart": "LambdaMART on logged labels",
    "lambdamart_debiased": "LambdaMART, LightGBM position debiasing",
    "torch_naive": "Network on logged labels",
    "torch_pbm": "Network, position-bias model",
    "ranker": "Shipping: position-bias model + fatigue + new-firm places",
}


def _read(name: str) -> Any:
    p = config.runs_dir() / name
    return json.loads(p.read_text()) if p.exists() else None


def _first(set_name: str) -> Any:
    p = config.REPORTS / "heldout" / set_name / "first_run.json"
    return json.loads(p.read_text()) if p.exists() else None


def report() -> dict[str, Any]:
    s = _read("study_test.json")
    train = _read("train.json")
    summary = json.loads((config.data_dir() / "logs" / "summary.json").read_text())
    release = (
        json.loads((config.REPORTS / "release.json").read_text())
        if (config.REPORTS / "release.json").exists()
        else {"ships": False, "gates": []}
    )
    blind = {n: _first(n) for n in ("blind-1", "blind-2")}
    res: dict[str, Any] = {
        "generated": dt.date.today().isoformat(),
        "profile": summary["profile"],
        "market": {
            k: summary[k]
            for k in ("months", "firms", "buyers", "lots", "impressions", "invited", "bids", "randomised_lots")
        },
        "policies": {k: {"label": LABELS[k], "offline": s["offline"][k], "replay": s["replay"][k]} for k in LABELS},
        "logged_mean": s["offline"]["_logged_mean"],
        "ab": s["ab"],
        "reader": s["reader"],
        "reader_vs_labels": train["readers"],
        "blind": {n: {k: b[k] for k in ("tfidf", "hash", "hybrid") if k in b} for n, b in blind.items() if b},
        "examination": s["examination"],
        "calibration": s["calibration"],
        "price": s["price"],
        "heldout_month": _first("month"),
        "agent": {k: v for k, v in (_read("agent.json") or {}).items() if k != "rows"} or None,
        "agent_no_model": {k: v for k, v in (_read("agent-no-model.json") or {}).items() if k != "rows"} or None,
        "bench": _read("bench.json"),
        "release": release,
    }
    config.REPORTS.mkdir(exist_ok=True)
    (config.REPORTS / "results.json").write_text(json.dumps(res, indent=1, ensure_ascii=False))
    (config.ROOT / "docs" / "REPORT.md").write_text(markdown(res))
    return res


def _f(v: Any, d: int = 3) -> str:
    return f"{v:.{d}f}" if isinstance(v, int | float) else str(v)


def markdown(r: dict[str, Any]) -> str:
    m = r["market"]
    L = [
        "# Report (generated by `tmr report`; do not edit)",
        "",
        f"Profile `{r['profile']}`: {m['months']} months, {m['firms']:,} firms, {m['buyers']} buyers, "
        f"{m['lots']:,} lots, "
        f"{m['impressions']:,} shortlist places logged, {m['invited']:,} invitations, {m['bids']:,} bids; "
        f"{m['randomised_lots']:,} lots served from a shuffled shortlist.",
        "",
        "## Offline estimates against the truth (test months, logged by the rules)",
        "",
        "Expected comparable bids per lot. *Truth* is the simulator's expectation for the same lots in the same "
        "market state; *replay* has every buyer use the policy for the whole test period, so fatigue shows.",
        "",
        "| Policy | NDCG on logs | IPS | Doubly robust | DR lift (95 %) | Truth | True lift | Support | Replay |",
        "|---|---:|---:|---:|---|---:|---:|---:|---:|",
    ]
    for p in r["policies"].values():
        o, rp = p["offline"], p["replay"]
        L.append(
            f"| {p['label']} | {_f(o['ndcg'])} | {_f(o['ips'])} | {_f(o['dr'])} | {_f(o['dr_lift'][0])} "
            f"({_f(o['dr_lift'][1])} to {_f(o['dr_lift'][2])}) | {_f(o['truth'])} | {_f(o['truth_lift'][0])} | "
            f"{o['support']:.0%} | {_f(rp['expected_competitive_per_lot'])} |"
        )
    L += [
        "",
        "## Market replay (every buyer on the policy, three months)",
        "",
        "| Policy | Comparable bids per lot | Bids per lot | Bid rate | Busiest 1 % of firms' share "
        "| New-firm places |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for p in r["policies"].values():
        rp = p["replay"]
        L.append(
            f"| {p['label']} | {_f(rp['expected_competitive_per_lot'])} | {_f(rp['bids_per_lot'], 2)} | "
            f"{rp['bid_rate']:.1%} | {rp['top1pct_invite_share']:.1%} | {rp['new_firm_slot_share']:.1%} |"
        )
    ab = r["ab"]
    L += [
        "",
        "## A/B test (buyers split 50/50, one shared market)",
        "",
        f"Plain: {_f(ab['plain']['effect'])} ({_f(ab['plain']['ci'][0])} to {_f(ab['plain']['ci'][1])}); "
        f"CUPED: {_f(ab['cuped']['effect'])} ({_f(ab['cuped']['ci'][0])} to {_f(ab['cuped']['ci'][1])}); "
        f"true effect of switching everyone: {_f(ab['true_effect'])} comparable bids per lot.",
        "",
        "| Look | Lots | z | O'Brien-Fleming bound | Stop |",
        "|---:|---:|---:|---:|---|",
    ]
    L += [
        f"| {s['look']} | {s['lots']} | {s['z']} | {s['bound']} | {'yes' if s['stop'] else 'no'} |"
        for s in ab["sequential"]
    ]
    rd = r["reader"]
    L += [
        "",
        "## Trade reader",
        "",
        f"Buyers' own trade label is right for {rd['buyer_label_right']:.1%} of test lots.",
        "",
        "Accuracy on the true trade. The blind sets were written by authors who never saw the code or the data; "
        "blind-1's first run had no model fallback (it led to it, docs/adr/0005); blind-2 was written afterwards.",
        "",
        "| Reader | Simulated test lots | blind-1, first run | blind-2, first run |",
        "|---|---:|---:|---:|",
    ]
    for k, label in (
        ("tfidf", "TF-IDF + logistic regression"),
        ("hash", "Hashed n-grams (PyTorch)"),
        ("hybrid", "Hashed n-grams + model for unsure lots"),
    ):
        sim = rd.get(k, {}).get("accuracy")
        b1 = r["blind"].get("blind-1", {}).get(k, {}).get("accuracy")
        b2 = r["blind"].get("blind-2", {}).get(k, {}).get("accuracy")
        cell = [f"{v:.1%}" if isinstance(v, float) else "–" for v in (sim, b1, b2)]
        L.append(f"| {label} | {cell[0]} | {cell[1]} | {cell[2]} |")
    ex = r["examination"]
    L += [
        "",
        "## Measured position bias",
        "",
        f"Examination by position, measured on the shuffled lots (max error vs the simulator's curve "
        f"{ex['max_abs_error']}): " + ", ".join(map(str, ex["estimated"][:10])) + " …",
        "",
        f"Calibration of P(invited and bid) on test: ECE {r['calibration']['ece']} (predicted "
        f"{r['calibration']['mean_predicted']}, observed {r['calibration']['mean_observed']}).",
        "",
        f"Price model on {r['price']['bids']:,} test bids: Brier for 'comparable' {r['price']['brier_competitive']} "
        f"(base rate {r['price']['brier_base_rate']}); pinball {r['price']['pinball']}.",
        "",
    ]
    if r.get("heldout_month"):
        h = r["heldout_month"]
        L += [
            "## Held-out month (first run, kept)",
            "",
            f"Rules {h['rules']['expected_competitive_per_lot']} vs ranker "
            f"{h['ranker']['expected_competitive_per_lot']} "
            f"comparable bids per lot ({h['lift']:+.1%}); monitoring alerts: {len(h['monitoring_alerts'])}.",
            "",
        ]
    if r.get("agent"):
        a = r["agent"]
        L += [
            "## Invite planner",
            "",
            f"{a['cases']} cases: extraction exact {a['extraction_exact']:.0%}, trades {a['trade_accuracy']:.0%}, "
            f"invariants broken {a['invariants_broken']}, decisions replaced by the verifier "
            f"{a['decisions_replaced_by_verifier']}, {a['calls']} model calls, ${a['cost_usd']}.",
            "",
        ]
    if r.get("bench"):
        L += [
            f"Serving: shortlist p50 {r['bench']['p50_ms']} ms, p95 {r['bench']['p95_ms']} ms over "
            f"{r['bench']['lots']} lots (in process).",
            "",
        ]
    L += [
        "## Release gate",
        "",
        "**Ships.**" if r["release"]["ships"] else "**Does not ship.**",
        "",
        "| Gate | Value | Limit | Result |",
        "|---|---:|---|---|",
    ]
    L += [
        f"| {g['gate']} | {g['value']} | {g['limit']} | {'pass' if g['pass'] else 'FAIL'} |"
        for g in r["release"]["gates"]
    ]
    return "\n".join(L) + "\n"
